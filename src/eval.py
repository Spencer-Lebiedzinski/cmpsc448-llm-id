"""Evaluation: accuracy, macro-F1, per-class report, (normalized) confusion matrix plot.

Usage:
  python -m src.eval --run_dir runs/cnn_output                 # re-evaluate a trained run on test
  python -m src.eval --run_dir runs/cnn_output --domains writing --tag writing
  python -m src.eval --summarize runs                          # table of all runs -> results/summary.md
"""
import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
import torch
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score

ROOT = Path(__file__).resolve().parents[1]


@torch.no_grad()
def predict(model, loader):
    model.eval()
    device = next(model.parameters()).device
    ys, ps = [], []
    for ids, lengths, y in loader:
        logits = model(ids.to(device), lengths.to(device))
        ps.append(logits.argmax(1).cpu().numpy())
        ys.append(y.numpy())
    return np.concatenate(ys), np.concatenate(ps)


def compute_metrics(y, p, labels):
    return {
        "n": int(len(y)),
        "accuracy": float(accuracy_score(y, p)),
        "macro_f1": float(f1_score(y, p, average="macro", labels=list(range(len(labels))), zero_division=0)),
        "chance_accuracy": float(1.0 / len(labels)),
        "per_class": classification_report(y, p, labels=list(range(len(labels))), target_names=labels,
                                           output_dict=True, zero_division=0),
    }


def plot_confusion(y, p, labels, path, title=""):
    cm = confusion_matrix(y, p, labels=list(range(len(labels))))
    cmn = cm / cm.sum(axis=1, keepdims=True).clip(min=1)
    fig, ax = plt.subplots(figsize=(1.2 * len(labels) + 2, 1.0 * len(labels) + 1.5))
    sns.heatmap(cmn, annot=cm, fmt="d", cmap="Blues", vmin=0, vmax=1, xticklabels=labels,
                yticklabels=labels, ax=ax, cbar_kws={"label": "row-normalized"})
    ax.set_xlabel("Predicted family")
    ax.set_ylabel("True family")
    ax.set_title(title)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return cm


def evaluate_and_save(model, loader, labels, out_dir: Path, tag: str = "test", title: str = ""):
    y, p = predict(model, loader)
    m = compute_metrics(y, p, labels)
    cm = plot_confusion(y, p, labels, out_dir / f"confusion_{tag}.png", title=title or tag)
    m["confusion_matrix"] = cm.tolist()
    m["labels"] = labels
    (out_dir / f"metrics_{tag}.json").write_text(json.dumps(m, indent=2))
    (out_dir / f"report_{tag}.txt").write_text(
        classification_report(y, p, labels=list(range(len(labels))), target_names=labels, zero_division=0))
    return m


def load_run(run_dir: Path):
    from .data.text import Vocab
    from .models import build_model
    cfg = json.loads((run_dir / "config.json").read_text())
    vocab = Vocab.load(run_dir / "vocab.json")
    labels = json.loads((run_dir / "labels.json").read_text())
    model = build_model(cfg, len(vocab), len(labels), vocab.pad_idx)
    model.load_state_dict(torch.load(run_dir / "model.pt", map_location="cpu"))
    return cfg, vocab, labels, model


def summarize(runs_root: Path, out_md: Path):
    rows = []
    for mf in sorted(runs_root.glob("*/metrics_*.json")):
        cfg = json.loads((mf.parent / "config.json").read_text())
        m = json.loads(mf.read_text())
        rows.append({"run": mf.parent.name, "eval": mf.stem.replace("metrics_", ""), "model": cfg["model"],
                     "input_mode": cfg["input_mode"], "ablation": cfg.get("ablation", "none"),
                     "train_domains": ",".join(cfg.get("train_domains") or []) or "all",
                     "train_n": cfg.get("train_n"), "epochs": cfg.get("epochs_run", cfg["epochs"]),
                     "n_eval": m["n"], "accuracy": round(m["accuracy"], 4), "macro_f1": round(m["macro_f1"], 4)})
    df = pd.DataFrame(rows)
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text("# Results summary (auto-generated by `python -m src.eval --summarize`)\n\n"
                      + (df.to_markdown(index=False) if len(df) else "_no runs found_") + "\n")
    print(df.to_string(index=False) if len(df) else "no runs")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run_dir", type=Path)
    ap.add_argument("--split", default="test")
    ap.add_argument("--domains", default="", help="comma-separated domain filter (RQ3)")
    ap.add_argument("--tag", default=None)
    ap.add_argument("--summarize", type=Path, help="runs root to summarize")
    ap.add_argument("--summary_out", type=Path, default=ROOT / "results" / "summary.md")
    args = ap.parse_args()
    if args.summarize:
        return summarize(args.summarize, args.summary_out)
    from .common import filter_domains, load_split, make_loader
    cfg, vocab, labels, model = load_run(args.run_dir)
    df = filter_domains(load_split(args.split), [d for d in args.domains.split(",") if d])
    df = df[df["family"].isin(labels)]
    loader = make_loader(df, cfg, vocab, {l: i for i, l in enumerate(labels)}, shuffle=False)
    tag = args.tag or (args.split + (f"_{args.domains.replace(',', '+')}" if args.domains else ""))
    m = evaluate_and_save(model, loader, labels, args.run_dir, tag=tag,
                          title=f"{cfg['model'].upper()} / {cfg['input_mode']} / {tag}")
    print(json.dumps({k: m[k] for k in ("n", "accuracy", "macro_f1")}, indent=2))


if __name__ == "__main__":
    main()
