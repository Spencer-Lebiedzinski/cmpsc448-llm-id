"""Mean and spread over seeds for runs repeated by scripts/run_seeds.ps1.

  python -m src.analysis.seed_summary            # runs/ (seed 42) + runs_seeds/seed*/ -> results/seed_summary.md
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]


def main():
    roots = [ROOT / "runs"] + sorted((ROOT / "runs_seeds").glob("seed*"))
    rows = []
    for root in roots:
        for mf in sorted(root.glob("*/metrics_test.json")):
            cfg = json.loads((mf.parent / "config.json").read_text())
            m = json.loads(mf.read_text())
            rows.append({"run": mf.parent.name, "seed": cfg["seed"], "accuracy": m["accuracy"],
                         "macro_f1": m["macro_f1"], "best_epoch": cfg["best_epoch"]})
    df = pd.DataFrame(rows)
    g = df.groupby("run")
    out = g.agg(n_seeds=("seed", "nunique"), acc_mean=("accuracy", "mean"), acc_std=("accuracy", "std"),
                acc_min=("accuracy", "min"), acc_max=("accuracy", "max"),
                f1_mean=("macro_f1", "mean"), f1_std=("macro_f1", "std"))
    out = out[out["n_seeds"] > 1].round(4)
    per_seed = df.pivot(index="run", columns="seed", values="accuracy").loc[out.index].round(4)
    md = ("# Seed variability (auto-generated by `python -m src.analysis.seed_summary`)\n\n"
          + out.to_markdown() + "\n\n## Test accuracy per seed\n\n" + per_seed.to_markdown() + "\n")
    (ROOT / "results" / "seed_summary.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
